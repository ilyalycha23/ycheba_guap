-- ЛР6, п. 6.4: вставка с «пополнением справочника» (аналог: студент + группа).
-- Приём на работу: если в справочнике «должность» нет строки с данным ид,
-- она добавляется, затем вставляется строка в «прием».

CREATE OR REPLACE PROCEDURE lr6_insert_hire_with_position(
    IN p_сотрудник int,
    IN p_подразделение int,
    IN p_должность int,
    IN p_дата date,
    IN p_совместительство bit(1)
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_next int;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM сотрудник WHERE ид = p_сотрудник) THEN
        RAISE EXCEPTION 'Сотрудник % не найден', p_сотрудник;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM подразделение WHERE ид = p_подразделение) THEN
        RAISE EXCEPTION 'Подразделение % не найдено', p_подразделение;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM должность WHERE ид = p_должность) THEN
        INSERT INTO должность (ид, наименование, категория)
        VALUES (
            p_должность,
            'LR6 должность id ' || p_должность::text,
            'прочее'
        );
    END IF;

    SELECT COALESCE(MAX(ид), 0) + 1 INTO v_next FROM прием;

    INSERT INTO прием (ид, ид_сотрудника, ид_подразделения, ид_должности, дата_приема, совместительство)
    VALUES (v_next, p_сотрудник, p_подразделение, p_должность, p_дата, p_совместительство);
END;
$$;

-- === Результат выполнения скрипта (вкладка Data Output) ===
-- Повторный запуск: сначала убираем строки прошлого демо с должностью 90.
DELETE FROM прием
WHERE ид_должности = 90 AND ид_сотрудника = 1 AND ид_подразделения = 2;
DELETE FROM должность
WHERE ид = 90 AND наименование LIKE 'LR6 должность%';

CALL lr6_insert_hire_with_position(1, 2, 90, CURRENT_DATE, B'0');

SELECT
    раздел,
    ид,
    наименование_или_фио,
    категория,
    ид_сотрудника,
    ид_подразделения,
    ид_должности,
    дата_приема,
    совместительство
FROM (
    SELECT
        'должность (справочник)'::text AS раздел,
        д.ид,
        д.наименование AS наименование_или_фио,
        д.категория,
        NULL::int AS ид_сотрудника,
        NULL::int AS ид_подразделения,
        NULL::int AS ид_должности,
        NULL::date AS дата_приема,
        NULL::text AS совместительство
    FROM должность д
    WHERE д.ид = 90

    UNION ALL

    SELECT
        'прием (новая строка)'::text,
        пр.ид,
        с.фио,
        NULL::varchar(50),
        пр.ид_сотрудника,
        пр.ид_подразделения,
        пр.ид_должности,
        пр.дата_приема,
        пр.совместительство::text
    FROM прием пр
    INNER JOIN сотрудник с ON с.ид = пр.ид_сотрудника
    WHERE пр.ид_должности = 90
      AND пр.ид_сотрудника = 1
      AND пр.ид_подразделения = 2
) AS результат
ORDER BY раздел, ид;
