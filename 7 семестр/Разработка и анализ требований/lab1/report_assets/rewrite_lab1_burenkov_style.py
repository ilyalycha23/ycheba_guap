FONT = "Times New Roman"


def set_run(run, size=14, bold=False, italic=False):
    run.font.name = FONT
    run._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    run.font.color.rgb = RGBColor(0, 0, 0)


def pfmt(p, align=WD_ALIGN_PARAGRAPH.JUSTIFY, first=1.25, before=0, after=0, line=1.5):
    pf = p.paragraph_format
    pf.alignment = align
    pf.first_line_indent = Cm(first) if first else Cm(0)
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    pf.line_spacing = line


def add_text(doc, text, *, size=14, bold=False, italic=False,
             align=WD_ALIGN_PARAGRAPH.JUSTIFY, first=1.25, before=0, after=0, line=1.5):
    p = doc.add_paragraph()
    pfmt(p, align=align, first=first, before=before, after=after, line=line)
    set_run(p.add_run(text), size=size, bold=bold, italic=italic)
    return p


def heading(doc, text, *, new_page=False):
    if new_page:
        p = doc.add_paragraph()
        pfmt(p, first=0, line=1.0)
        run = p.add_run()
        run.add_break(WD_BREAK.PAGE)
    return add_text(doc, text, bold=True, align=WD_ALIGN_PARAGRAPH.CENTER,
                    first=0, before=12, after=12)


def sub(doc, text):
    return add_text(doc, text, bold=True, align=WD_ALIGN_PARAGRAPH.LEFT,
                    first=0, before=10, after=6)


def shade(cell, color="D9E2F3"):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:fill"), color)
    shd.set(qn("w:val"), "clear")
    tcPr.append(shd)


def cell_text(cell, text, *, bold=False, size=11, align=WD_ALIGN_PARAGRAPH.LEFT):
    cell.text = ""
    p = cell.paragraphs[0]
    p.alignment = align
    pf = p.paragraph_format
    pf.space_before = Pt(2)
    pf.space_after = Pt(2)
    pf.line_spacing = 1.0
    pf.first_line_indent = Cm(0)
    set_run(p.add_run(text), size=size, bold=bold)


def add_table(doc, headers, rows, col_widths=None):
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        cell_text(table.rows[0].cells[i], h, bold=True, size=11, align=WD_ALIGN_PARAGRAPH.CENTER)
        shade(table.rows[0].cells[i])
    for r, row in enumerate(rows, start=1):
        for c, val in enumerate(row):
            align = WD_ALIGN_PARAGRAPH.CENTER if c == 0 else WD_ALIGN_PARAGRAPH.LEFT
            cell_text(table.rows[r].cells[c], str(val), size=11, align=align)
    if col_widths:
        for row in table.rows:
            for i, w in enumerate(col_widths):
                row.cells[i].width = Cm(w)
    doc.add_paragraph()
    return table


def add_kv_table(doc, rows, left_w=4.0, right_w=12.5, shade_left=True):
    table = doc.add_table(rows=len(rows), cols=2)
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, (left, right) in enumerate(rows):
        cell_text(table.rows[i].cells[0], left, bold=True, size=11)
        if shade_left:
            shade(table.rows[i].cells[0], "E7E6E6")
        cell_text(table.rows[i].cells[1], right, size=11)
        table.rows[i].cells[0].width = Cm(left_w)
        table.rows[i].cells[1].width = Cm(right_w)
    doc.add_paragraph()
    return table


def clear_after_title(doc, keep_count: int):
    """Удалить все дочерние элементы body после keep_count, кроме sectPr."""
    body = doc.element.body
    children = list(body.iterchildren())
    # last child is usually sectPr — never delete it
    to_remove = []
    for i, child in enumerate(children):
        tag = child.tag.split("}")[-1]
        if tag == "sectPr":
            continue
        if i >= keep_count:
            to_remove.append(child)
    for child in to_remove:
        body.remove(child)


