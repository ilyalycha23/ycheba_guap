%% LR2: MATLAB figure generation from selfie (real IPT functions + print)
clc; close all; clearvars;
set(0, 'DefaultFigureVisible', 'off');

base = 'C:\temp\lab2';
outDir = fullfile(base, 'screenshots');
logDir = fullfile(base, 'capture');
if ~exist(outDir, 'dir'); mkdir(outDir); end
if ~exist(logDir, 'dir'); mkdir(logDir); end

I0 = im2uint8(imread(fullfile(base, 'source_selfie.jpg')));
nFrames = 180;
fps = 30;
pad = 28;
Ip = padarray(I0, [pad pad], 'replicate', 'both');
[h0, w0, ~] = size(I0);

seq = cell(nFrames, 1);
[Hp, Wp, ~] = size(Ip);
for k = 1:nFrames
    dx = round(10 * sin(2*pi*k/45));
    dy = round(6 * cos(2*pi*k/60));
    if k > 90
        dx = dx + round(14 * sin(2*pi*(k-90)/25));
        dy = dy + round(8 * cos(2*pi*(k-90)/30));
    end
    x = max(1, min(pad + 1 + dx, Wp - w0 + 1));
    y = max(1, min(pad + 1 + dy, Hp - h0 + 1));
    seq{k} = Ip(y:y+h0-1, x:x+w0-1, :);
end

I640 = imresize(seq{1}, [480 640]);
I720 = imresize(seq{1}, [720 1280]);
I640b = imresize(seq{22}, [480 640]);
I640c = imresize(seq{110}, [480 640]);

