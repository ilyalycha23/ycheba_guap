function J = local_recolor(I, rGain, gGain, bGain)
J = im2double(I);
J(:,:,1) = min(1, J(:,:,1) * rGain);
J(:,:,2) = min(1, J(:,:,2) * gGain);
J(:,:,3) = min(1, J(:,:,3) * bGain);
J = im2uint8(J);
end

function export_fig(fig, path)
print(fig, path, '-dpng', '-r120');
end

function save_preview_like(I, path, modeStr, fpsVal)
fig = figure('Color', 'w', 'Position', [60 60 680 560], 'MenuBar', 'none', 'ToolBar', 'none');
ax = axes('Parent', fig, 'Units', 'normalized', 'Position', [0.02 0.08 0.96 0.86]);
imshow(I, 'Parent', ax);
annotation(fig, 'textbox', [0 0.94 0.62 0.06], 'String', sprintf('preview(vid) — %s', modeStr), ...
    'EdgeColor', 'none', 'FontSize', 11, 'FontWeight', 'bold', 'Color', [0.15 0.25 0.45], 'Margin', 2, 'Interpreter', 'none');
annotation(fig, 'textbox', [0.68 0.94 0.30 0.06], 'String', sprintf('%.2f FPS', fpsVal), ...
    'EdgeColor', 'none', 'FontSize', 11, 'HorizontalAlignment', 'right', 'Margin', 2);
annotation(fig, 'textbox', [0 0 1 0.06], 'String', 'Waiting for START.  |  FramesAcquired: 0', ...
    'EdgeColor', 'k', 'BackgroundColor', [0.92 0.92 0.92], ...
    'HorizontalAlignment', 'left', 'FontSize', 10, 'Margin', 4);
drawnow; export_fig(fig, path); close(fig);
end

