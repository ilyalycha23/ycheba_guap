function Update-ContentTags($text) {
    foreach ($key in $replacements.Keys) {
        $val = $replacements[$key]
        $text = [regex]::Replace($text, "(<v8:content>)$([regex]::Escape($key))(</v8:content>)", "`${1}$val`${2}")
        $text = [regex]::Replace($text, '(<title xsi:type="xs:string">)' + [regex]::Escape($key) + '(</title>)', "`${1}$val`${2}")
    }
    return $text
}

Get-ChildItem $src -Recurse -Include *.xml | ForEach-Object {
    $content = [System.IO.File]::ReadAllText($_.FullName)
    $updated = Update-ContentTags $content
    if ($updated -ne $content) {
        [System.IO.File]::WriteAllText($_.FullName, $updated, [System.Text.UTF8Encoding]::new($false))
    }
}
